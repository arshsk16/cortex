"""Agent result data classes."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from cortex.retrieval.models import RetrievalResult


@dataclass(frozen=True, slots=True)
class ToolCallRecord:
    """Record of a single tool invocation within an agent run.

    Attributes
    ----------
    tool_name:
        The tool that was called.
    args:
        Arguments passed to the tool.
    observation:
        The plain-text result returned by the tool.
    """

    tool_name: str
    args: dict[str, Any]
    observation: str


@dataclass
class AgentResult:
    """Result returned by :meth:`~cortex.agent.service.AgentService.run`.

    Attributes
    ----------
    answer:
        The final grounded answer generated by the LLM.
    tool_calls:
        Ordered list of every tool invocation made during this agent run.
    retrieved_chunks:
        All :class:`~cortex.retrieval.models.RetrievalResult` objects
        accumulated across all RAG search tool calls.  These are used by
        the endpoint to build citation metadata, following the same
        pattern as :class:`~cortex.services.rag.RAGResult`.
    """

    answer: str
    tool_calls: list[ToolCallRecord] = field(default_factory=list)
    retrieved_chunks: list[RetrievalResult] = field(default_factory=list)
